  @Test("The trace is the one measured off the take, not a synthetic stand-in")
  func traceMatchesWhatWasMeasured() {
    let values = Self.impliedOriginMilliseconds.map { Double($0) / 1_000 }
    #expect(values.count == 2_415)
    let net = values[values.count - 1] - values[0]
    let travelled = (1 ..< values.count).reduce(0.0) { $0 + abs(values[$1] - values[$1 - 1]) }
    #expect(abs(net - 0.114) < 0.001, "net drift \(net) s")
    #expect(abs(travelled - 59.67) < 0.05, "total variation \(travelled) s")
    // The signal it followed is bounded well under a second; the loss was 50.00 s.
    #expect((values.max() ?? 0) - (values.min() ?? 0) < 0.5)
  }

  /// What the old writer did, reduced to the part that mattered: place sound at
  /// `captureWall + contentOffset`, reseat when that strays past the deadband, and — because an
  /// MP4 audio track cannot express a discontinuity — lose the difference either way. A move later
  /// left a gap the muxer closed; a move earlier dropped buffers. Returns seconds of sound lost.
  private func lossUnderTheOldRule(deadband: Double = 0.1) -> Double {
    let values = Self.impliedOriginMilliseconds.map { Double($0) / 1_000 }
    var epoch = values[0]
    var lost = 0.0
    for value in values {
      let strayed = value - epoch
      if abs(strayed) > deadband {
        lost += abs(strayed)
        epoch = value
      }
    }
    return lost
  }

  @Test("The fixture really does exercise the fault: the old rule loses seconds on this trace")
  func theOldRuleLoses() {
    // 14.8 s at this 3 s sampling. The file lost 50.00 s, because the real writer saw the same
    // signal 150 times more often — 20 ms chunks, not 3 s anchors — and crossed the deadband far
    // more. Either way it is seconds, not milliseconds, and it is all one-way.
    let lost = lossUnderTheOldRule()
    #expect(lost > 10, "old rule lost only \(lost) s, so this trace no longer reproduces the fault")
    #expect(abs(Self.picturedSeconds - Self.soundSeconds - 50.00) < 0.01)
  }

  @Test("The origin settles once on this trace and then never moves")
  func originSettlesOnce() {
    var origin = ProgrammeSoundOrigin()
    var programme = 0.0
    for value in Self.impliedOriginMilliseconds.map({ Double($0) / 1_000 }) {
      origin.offer(impliedPartStart: value, atProgramme: programme)
      programme += Self.anchorInterval
    }
    let settled = try? #require(origin.partStartWall)
    #expect(settled != nil)
    // Seeded from the opening alone: with anchors 3 s apart the seed closes on the first sample
    // past 1.5 s, so the whole rest of the game cannot move it.
    #expect(origin.isSettled)
  }

  /// The invariant, against the real trace: every 20 ms chunk of a 7245 s game is placed, in order,
  /// contiguously, and the sound comes out exactly as long as the take. No deadband, nothing to
  /// cross, nothing to lose.
  @Test("Replaying the whole game places every chunk and loses nothing")
  func replayLosesNothing() {
    var origin = ProgrammeSoundOrigin()
    let partStart = 1_000.0
    var programme = 0.0
    for value in Self.impliedOriginMilliseconds.map({ Double($0) / 1_000 }) {
      origin.offer(impliedPartStart: partStart + value, atProgramme: programme)
      programme += Self.anchorInterval
    }
    let settled = origin.partStartWall ?? partStart

    let chunk = 0.02
    let chunks = Int(Self.picturedSeconds / chunk)
    var placed = 0
    var previous = -1.0
    for index in 0 ..< chunks {
      // The mix is gapless and real-time: one chunk per 20 ms of wall clock, stamped with capture.
      let wall = settled + Double(index) * chunk
      guard let time = origin.timeline(forCaptureWall: wall) else {
        Issue.record("chunk \(index) at \(wall) was dropped")
        return
      }
      #expect(time > previous, "chunk \(index) went backwards")
      previous = time
      placed += 1
    }
    #expect(placed == chunks, "placed \(placed) of \(chunks) chunks")
    // Sound as long as the take, to within one chunk.
    let sound = previous + chunk
    #expect(
      abs(sound - Double(chunks) * chunk) < chunk,
      "sound spans \(sound) s against \(Double(chunks) * chunk) s of take"
    )
  }
